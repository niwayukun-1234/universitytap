delete from public.buildings b
where b.university_id = 'doshisha'
  and not exists (select 1 from public.classrooms c where c.building_id = b.id)
  and not exists (select 1 from _ut_rooms r where r.campus = b.campus and r.building = b.name);

-- 館
insert into public.buildings (name, campus, university_id, sort_order)
select distinct r.building, r.campus, 'doshisha', r.building_order
from _ut_rooms r
where not exists (
  select 1 from public.buildings b
  where b.university_id = 'doshisha' and b.campus = r.campus and b.name = r.building
);

update public.buildings b
set sort_order = r.building_order
from (select distinct campus, building, building_order from _ut_rooms) r
where b.university_id = 'doshisha' and b.campus = r.campus and b.name = r.building;

-- 教室
insert into public.classrooms (name, building_id, university_id, floor_label, floor_order, sort_order)
select r.name, b.id, 'doshisha', r.floor_label, r.floor_order, r.room_order
from _ut_rooms r
join public.buildings b on b.university_id = 'doshisha' and b.campus = r.campus and b.name = r.building
where not exists (
  select 1 from public.classrooms c where c.building_id = b.id and c.name = r.name
);

update public.classrooms c
set floor_label = r.floor_label, floor_order = r.floor_order, sort_order = r.room_order
from _ut_rooms r
join public.buildings b on b.university_id = 'doshisha' and b.campus = r.campus and b.name = r.building
where c.building_id = b.id and c.name = r.name;

drop table if exists _ut_rooms;
